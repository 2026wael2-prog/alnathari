import { describe, it, expect } from 'vitest';
import { tafqeet } from './tafqeet';

/**
 * يُثبّت سلوك التفقيط بعد إصلاح أربعة عيوب:
 *  - NaN كان يُدخل convertGroup في استدعاء ذاتي لا نهائي (RangeError).
 *  - 1e9 كان يُقرأ «ألف مليون» بدل «مليار».
 *  - 1.999 كان يصبح «واحد و مئة هللة» بدل «اثنين» (لا ترحيل للكسور).
 *  - الإشارة السالبة كانت تُهمل.
 */
describe('tafqeet', () => {
  it('يفقّط الصفر والعملة', () => {
    expect(tafqeet(0, 'ر.س')).toBe('صفر ر.س');
  });

  it('يفقّط الأعداد الأساسية', () => {
    expect(tafqeet(1, 'ر.س')).toBe('واحد ر.س');
    expect(tafqeet(250, 'ر.س')).toBe('مئتان و خمسون ر.س');
    expect(tafqeet(3000, 'ر.س')).toBe('ثلاثة آلاف ر.س');
    expect(tafqeet(1500000, 'ر.س')).toBe('مليون و خمسمئة ألف ر.س');
  });

  it('يدعم المليار والتريليون بوزنها الصحيح', () => {
    expect(tafqeet(1_000_000_000, 'ر.س')).toBe('مليار ر.س');
    expect(tafqeet(1_000_000_000_000, 'ر.س')).toBe('تريليون ر.س');
  });

  it('يرحّل الكسور إلى الصحيح بدل مضاعفة الهللات', () => {
    expect(tafqeet(1.999, 'ر.س')).toBe('اثنان ر.س');
    expect(tafqeet(100.5, 'ر.س')).toBe('مئة و خمسون هللة ر.س');
  });

  it('يحفظ الإشارة السالبة', () => {
    expect(tafqeet(-500, 'ر.س')).toBe('سالب خمسمئة ر.س');
  });

  it('يشتق اسم الكسر من العملة', () => {
    expect(tafqeet(1.25, 'ريال يمني')).toBe('واحد و خمسة و عشرون فلس ريال يمني');
    expect(tafqeet(2.5, 'دولار أمريكي')).toBe('اثنان و خمسون سنت دولار أمريكي');
  });

  it('لا ينهار على قيمة غير منتهية', () => {
    expect(tafqeet(Number.NaN)).toBe('');
    expect(tafqeet(Number.POSITIVE_INFINITY)).toBe('');
  });
});
